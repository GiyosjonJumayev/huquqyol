def _region_names(lat):
    if lat.endswith(" shahri"): base = lat[:-7] + " shahar"; return base + " hokimligi", base + " prokuraturasi", lat + " bo‘yicha"
    if lat.endswith("Respublikasi"): return lat + " Vazirlar Kengashi", lat + " prokuraturasi", lat + " bo‘yicha"
    return lat + " hokimligi", lat + " prokuraturasi", lat + " bo‘yicha"

def build():
    regions = []
    for line in RAW.strip().splitlines():
        line = line.strip()
        if not line: continue
        if line.startswith("#"):
            name, center = [x.strip() for x in line[1:].split("|")]
            lat_center = to_latin(center)
            hok, prok, by = _region_names(to_latin(name))
            rh, rp, rb = RU_REGION[name]
            regions.append({"name": to_latin(name), "cyr": name, "center": lat_center,
                            "admin": lat_center + " tumanlararo ma’muriy sudi", "adminCyr": center + " туманлараро маъмурий суди",
                            "hokimlik": hok, "prokuratura": prok, "by": by, "ru": {"hokimlik": rh, "prokuratura": rp, "by": rb},
                            "districts": []})
            continue
        court, places = [x.strip() for x in line.split("|")]
        civ, civ_cyr = _civil(court)
        for p in places.split(";"):
            d = _place(p)
            d.update({"civil": civ, "civilCyr": civ_cyr})
            regions[-1]["districts"].append(d)
    names = [(r["name"], d["name"]) for r in regions for d in r["districts"]]
    assert len(names) == len(set(names)), "takror tuman"
    assert len(regions) == 14, len(regions)
    return {"checked": CHECKED, "source": SOURCE, "regions": regions}
