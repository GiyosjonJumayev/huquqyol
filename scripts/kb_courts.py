# O‘zbek kirill → lotin (rasmiy alifbo). «е» so‘z boshida va unlidan keyin «ye», «ц» — «s».
_V = set("аеёиоуэюяўАЕЁИОУЭЮЯЎ")
_M = {"а":"a","б":"b","в":"v","г":"g","д":"d","ж":"j","з":"z","и":"i","й":"y","к":"k","л":"l","м":"m","н":"n","о":"o",
      "п":"p","р":"r","с":"s","т":"t","у":"u","ф":"f","х":"x","ц":"s","ч":"ch","ш":"sh","щ":"sh","ъ":"’","ь":"","ы":"i",
      "э":"e","ю":"yu","я":"ya","ё":"yo","ў":"o‘","қ":"q","ғ":"g‘","ҳ":"h"}
def to_latin(s):
    out = []
    for i, ch in enumerate(s):
        low = ch.lower()
        if low == "е":
            prev = s[i - 1] if i else " "
            lat = "ye" if (not prev.isalpha() or prev in _V) else "e"
        elif low in _M: lat = _M[low]
        else: out.append(ch); continue
        if ch != low and lat: lat = lat[0].upper() + lat[1:]
        out.append(lat)
    return "".join(out)

def _place(cyr):
    """«Нукус шаҳар» → {"name":"Nukus shahri", "kind":"shahar"}; «Амударё тумани» → {"name":"Amudaryo tumani", "kind":"tuman"}."""
    cyr = cyr.strip()
    if cyr.endswith(" шаҳар"): return {"name": to_latin(cyr[:-6]) + " shahri", "kind": "shahar", "cyr": cyr[:-6] + " шаҳри"}
    assert cyr.endswith(" тумани"), cyr
    return {"name": to_latin(cyr), "kind": "tuman", "cyr": cyr}

def _civil(cyr_court):
    """«Беруний туманлараро суди» → «Fuqarolik ishlari bo‘yicha Beruniy tumanlararo sudi» (lotin va kirill)."""
    return "Fuqarolik ishlari bo‘yicha " + to_latin(cyr_court), "Фуқаролик ишлари бўйича " + cyr_court

